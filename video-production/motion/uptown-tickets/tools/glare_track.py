#!/usr/bin/env python3
"""Tracks the venue's big work light (the brightest blob in the top half of frame) so the moon can sit on it.

  python3 glare_track.py <frames_dir> <out.js>     -> window.GLARE = [[x, y, size], ...] per frame (full-res px)
"""
import sys, os, json, glob
import numpy as np
from PIL import Image

frames = sorted(glob.glob(os.path.join(sys.argv[1], "f_*.jpg")))
out = []
for f in frames:
    im = np.asarray(Image.open(f).convert("L").resize((270, 480)), np.float32)
    top = im[:240]
    m = top > 246
    if m.sum() < 6:
        out.append(None); continue
    ys, xs = np.nonzero(m)
    out.append([float(xs.mean() * 4), float(ys.mean() * 4), float(np.sqrt(m.sum()) * 4)])
# fill gaps from neighbours, then smooth lightly
last = None
for i in range(len(out)):
    if out[i] is None: out[i] = last
    else: last = out[i]
nxt = None
for i in range(len(out) - 1, -1, -1):
    if out[i] is None: out[i] = nxt
    else: nxt = out[i]
a = np.array([o if o else [540, 300, 0] for o in out], np.float32)
k = np.array([1, 2, 3, 2, 1], np.float32); k /= k.sum()
sm = np.stack([np.convolve(np.pad(a[:, i], 2, mode="edge"), k, mode="valid") for i in range(3)], 1)
with open(sys.argv[2], "w") as fh:
    fh.write("// generated by tools/glare_track.py\nwindow.GLARE = " + json.dumps(np.round(sm, 1).tolist()) + ";\n")
print(len(sm), "frames; x", sm[:, 0].min(), sm[:, 0].max(), "y", sm[:, 1].min(), sm[:, 1].max())
