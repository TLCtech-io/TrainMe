#!/usr/bin/env python3
"""Packs data/words.json and the feature tracks into data/data.js (a file:// page cannot fetch JSON)."""
import json, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
words = json.load(open(os.path.join(root, "words.json")))
tracks = {k: json.load(open(os.path.join(root, f"track_{k}.json"))) for k in ("thermo", "closet")}
with open(os.path.join(root, "data.js"), "w") as f:
    f.write("// generated by tools/make-data.py\n")
    f.write("window.WORDS = " + json.dumps([[w["w"], w["s"], w["e"]] for w in words]) + ";\n")
    f.write("window.TRACKS = " + json.dumps(tracks) + ";\n")
print(len(words), "words,", ", ".join(f"{k} {len(v['xy'])} frames" for k, v in tracks.items()))
