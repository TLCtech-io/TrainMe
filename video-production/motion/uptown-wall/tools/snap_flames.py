#!/usr/bin/env python3
"""Snap hand-placed candle flames to their bright cores and measure them (the loop flickers each one).

  python tools/snap_flames.py assets/plate.png data/flames.js

APPROX are rough flame positions read off the plate by eye (plate pixels); each is moved to the brightest point within
60 px, and its height runs from there up the centre column to where it fades (width from the usual proportions). The last
entry is the green spirit-lamp flame under the green flask (kind 1).
"""
import sys
import numpy as np
from PIL import Image
from scipy import ndimage as ndi

APPROX = [  # x, y, kind (0 candle, 1 green burner)
    (310, 1000, 0), (433, 1025, 0), (4347, 975, 0), (5105, 1030, 0), (5210, 1000, 0), (4978, 1492, 0), (5068, 1472, 0),
    (1778, 1910, 0), (1876, 1948, 0), (3640, 1915, 0), (3744, 1866, 0),
    (252, 2161, 0), (413, 2294, 0), (2060, 2114, 0), (2018, 2256, 0), (3448, 2138, 0), (3568, 2314, 0), (5154, 2323, 0),
    (1345, 2179, 1),
]
a = np.asarray(Image.open(sys.argv[1]).convert("RGB"), np.float32) / 255
L = ndi.gaussian_filter(a @ np.array([0.299, 0.587, 0.114], np.float32), 2)
out = []
for x, y, kind in APPROX:
    r = 60
    win = L[y - r:y + r, x - r:x + r]
    iy, ix = np.unravel_index(np.argmax(win), win.shape)
    cx, cy = x - r + ix, y - r + iy
    peak = L[cy, cx]
    # the flame is the bright tongue above the core: walk up the centre column to where it fades (the wax below is
    # bright too, so width comes from the flame's usual proportions, not from a threshold)
    tip = cy
    while tip > cy - 200 and L[tip - 1, cx - 3:cx + 4].max() > 0.55 * peak: tip -= 1
    h = min(86, max(24, int((cy - tip) * 1.35)))                 # a neighbouring lit candle can stretch the walk
    out.append([int(cx), int(cy), int(round(h * 0.36)), h, kind])
open(sys.argv[2], "w").write("// generated by tools/snap_flames.py: flames [x, y (bright core), w, h, kind] in plate pixels; kind 1 = the green burner\n"
                             "window.FLAMES = " + str(out) + ";\n")
for f in out: print(f)
