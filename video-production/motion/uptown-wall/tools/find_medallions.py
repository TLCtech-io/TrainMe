#!/usr/bin/env python3
"""Find the two brass medallions beside the UPTOWN SOUND sign in a plate (they can drift a little between edits).

  python tools/find_medallions.py assets/plate.png data/medallions.js

Searches near the expected centres for the circle whose rim has the strongest radial edge (the polished rim against
the dark wood), then reports each centre and the radius of the flat face inside the rim (rim radius minus the rim's
width). Writes them as window.MEDALS for index.html.
"""
import sys
import numpy as np
from PIL import Image, ImageFilter

im = Image.open(sys.argv[1]).convert("L")
W, H = im.size
S = 4                                             # work at quarter resolution, refine at full
small = np.asarray(im.resize((W // S, H // S)).filter(ImageFilter.GaussianBlur(1.5)), np.float32)
gy, gx = np.gradient(small)
th = np.linspace(0, 2 * np.pi, 180, endpoint=False)

def score(cx, cy, r):
    xs, ys = cx + r * np.cos(th), cy + r * np.sin(th)
    ok = (xs > 1) & (ys > 1) & (xs < small.shape[1] - 2) & (ys < small.shape[0] - 2)
    xi, yi = xs[ok].astype(int), ys[ok].astype(int)
    radial = gx[yi, xi] * np.cos(th[ok]) + gy[yi, xi] * np.sin(th[ok])   # dark outside, bright rim: negative outward
    return -radial.mean() if ok.sum() > 150 else -1e9

out = []
for ex, ey in ((0.13 * W, 0.123 * H), (0.87 * W, 0.123 * H)):
    best = (-1e9, 0, 0, 0)
    for cy in np.arange((ey - 120) / S, (ey + 120) / S, 2):
        for cx in np.arange((ex - 160) / S, (ex + 160) / S, 2):
            for r in np.arange(180 / S, 250 / S, 1.5):
                v = score(cx, cy, r)
                if v > best[0]: best = (v, cx, cy, r)
    _, cx, cy, r = best
    out.append([round(cx * S), round(cy * S), round(r * S * 0.84)])     # the face is ~84% of the outer rim
    print(f"centre ({cx * S:.0f}, {cy * S:.0f}) rim r {r * S:.0f}", file=sys.stderr)
open(sys.argv[2], "w").write("// generated by tools/find_medallions.py: [centre x, centre y, face radius] in plate pixels\nwindow.MEDALS = " + str(out) + ";\n")
print(out)
